# Simple calculator using functions

#The processes for each function
def add(num1, num2):
  return num1 + num2

def subtract(num1, num2):
  return num1 - num2

def multiply(num1, num2):
  return num1 * num2

def divide(num1, num2):
  return num1 / num2

#Get input from the user
try:
    num1 = float(input("Enter the first number: "))
    num2 = float(input("Enter the second number: "))
    valid = True
except ValueError:
    print("Error: please enter numbers only.")
    valid = False

#To check if the input is valid
if valid:

  #Choose an operation to use
  print("Type 1 to choose Addition")
  print("Type 2 to choose Subtraction")
  print("Type 3 to choose Multiplication")
  print("Type 4 to choose Division")

  choice = input("Enter your choice (1-4): ")

  #Call the function that matches the choice
  if choice == "1":
    result = add(num1, num2)
    print("Result:", result)

  elif choice == "2":
    result = subtract(num1, num2)
    print("Result:", result)

  elif choice == "3":
    result = multiply(num1, num2)
    print("Result:", result)

  elif choice == "4":
    if num2 == 0:
      print("Error: cannot divide by zero")
    else:
      result = divide(num1, num2)
      print("Result:", result)

  else:
    print("Invalid choice. Please enter a number from 1 to 4.")